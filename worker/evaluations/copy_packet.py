"""Writes docs/ai-coach-copy-review-2026-10-31.md: every sentence the coach says without a model, for one Hungarian read-through.

  python3 worker/evaluations/copy_packet.py        # from the repository root

The sentences come from the code itself (coach_router constants, plain_checkin templates, the authored content files),
so the packet cannot drift from what players are shown. Re-run it after changing any wording.
"""
import json
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "worker"))
from habi_worker import coach_router as cr, plain_checkin as pc  # noqa: E402

OUT = ROOT / "docs" / "ai-coach-copy-review-2026-10-31.md"
NODE = """
const g = await import('./src/lib/workflows/guided-conversations.mjs');
const c = await import('./src/lib/workflows/coach-guidance.mjs');
const routing = JSON.parse(await (await import('node:fs/promises')).readFile('./src/lib/content/guided-chat-routing-v1.json','utf8'));
console.log(JSON.stringify({safety: g.guidedConversationSafetyReply().text, pain: c.painGuidanceReply().text, safetyKeywords: routing.safetyKeywords, painKeywords: routing.painKeywords}));
"""


def authored():
    run = subprocess.run(["node", "--input-type=module", "-e", NODE], cwd=ROOT, capture_output=True, text=True, check=True)
    return json.loads(run.stdout)


def checkin_samples():
    date = datetime(2026, 10, 27, 11, 28, tzinfo=ZoneInfo("Europe/Budapest"))
    facts = [{"key": "sleep", "variants": [pc.PHRASES["player"]["sleep"][2]]}, {"key": "mood", "variants": [pc.PHRASES["player"]["mood"][3]]}]
    other = [{"key": "sleep", "variants": [pc.PHRASES["other"]["sleep"][2]]}, {"key": "mood", "variants": [pc.PHRASES["other"]["mood"][3]]}]
    context = {"turnRevision": 1, "playerName": "Teszt Csaba", "promptManifest": {}}
    out = {}
    for role, f in (("player", facts), ("other", other)):
        bundle = {"date": date, "facts": f, "role": role, "ref": {}, "source": {"text": ""}}
        answer = pc.plain_answer(context, bundle, pc.default_text(bundle))
        out[role] = (answer["claims"][0]["text"], answer["clarifyingQuestions"][0])
    return out


def row(where, when, text):
    cell = text.replace("|", "\\|").replace("\n", " ")
    return f"| {where} | {when} | {cell} |"


def main():
    a = authored()
    samples = checkin_samples()
    lines = [
        "# AI coach: wording review packet · 2026-10-31",
        "",
        "Generated by `worker/evaluations/copy_packet.py` from the code and the authored content files. Every sentence below is what a player, coach or parent can read without a model writing it. Nothing here has had a Hungarian copy review yet.",
        "",
        "## How to review",
        "",
        "For each row: is it natural Hungarian, is the address right (te for the player; the coach and parent texts name the player), does it claim anything that did not happen, and is the tone right for a young person? Mark OK or write the replacement. The rows marked **new wording** are the ones I wrote; the others reuse authored text.",
        "",
        "## 1. Rule answers (`habi_worker/coach_router.py`)",
        "",
        "| Where | When | Text |",
        "|---|---|---|",
        row("NO_CHECKIN_TEXT", "a status question and no check-in exists", cr.NO_CHECKIN_TEXT),
        row("NO_METRIC_TEXT", "the asked area has no recorded answer", cr.NO_METRIC_TEXT),
        row("ADVICE_DECLINE + ADVICE_RECORDED_LEAD", "“Mit tanácsolsz…”, “Mit gondolsz…”, “hogyan javíthatnám…”; then the dated check-in follows", cr.ADVICE_DECLINE + cr.ADVICE_RECORDED_LEAD + "a 2026. október 27-i beszámolódban azt jelezted, hogy …"),
        row("ADVICE_NO_CHECKIN", "same, when there is no check-in", cr.ADVICE_DECLINE + cr.ADVICE_NO_CHECKIN),
        row("CONFIRMATION_TEMPLATE", "“Tényleg?”, “Biztos vagy ebben?”, “Mi alapján?” right after a check-in summary", cr.CONFIRMATION_TEMPLATE.format(date="2026. október 27-i")),
        row("GREETING_TEXT", "“Szia!”", cr.GREETING_TEXT),
        row("LATER_REPORTS", "a repeated status question after newer reports", cr.LATER_REPORTS_LEAD + "„…az üzenet szó szerint…”. " + cr.LATER_REPORTS_QUESTION),
        row("FALLBACK_TEXT", "the model's reply was refused twice", cr.FALLBACK_TEXT),
    ]
    for kind, text in cr.ACKNOWLEDGEMENTS.items():
        lines.append(row(f"ACKNOWLEDGEMENTS[{kind}]", f"a message that is a {kind}, not a question", text))
    lines += [
        "",
        "## 2. Check-in summary (`habi_worker/plain_checkin.py`, live since 2026-10-28)",
        "",
        "| Where | When | Text |",
        "|---|---|---|",
        row("plain_answer, player", "status question, shown to the player (example: keveset aludtál, feszültnek érezted magad)", samples["player"][0] + " " + samples["player"][1]),
        row("plain_answer, coach/parent", "same, shown to a coach or parent", samples["other"][0] + " " + samples["other"][1]),
        "",
        "## 3. Safety and pain (authored, one message each)",
        "",
        "The safety message is the authored `safety` node (response, question) plus the authored outcomes `immediate-adult` and `adult-today`. **New wording:** only the two joining phrases “Ha nem, vagy nem tudod biztosan:” and “Ha igen, de beszélnél róla:”.",
        "",
        "> " + a["safety"],
        "",
        "The pain message is stored in `src/lib/content/coach-guidance-v1.json` (`pain-or-illness`). It reuses the authored clause “Ha fáj valamid, beteg vagy vagy rosszul vagy, … ne erőltesd az edzést.” (the “vele” became “az edződdel vagy egy megbízható felnőttel”). **New wording:** the opening “Köszönöm, hogy megírtad.” and the last sentence “Ha erős a fájdalom, szédülsz vagy nehezen kapsz levegőt, szólj azonnal egy felnőttnek.”",
        "",
        "> " + a["pain"],
        "",
        "## 4. Screen text (`src/app/ai-coach.tsx`)",
        "",
        "| Where | When | Text |",
        "|---|---|---|",
        row("answer label", "every answer a model wrote (not a rule)", "Kísérleti AI-válasz: nem ellenőrzött. Fontos kérdésben kérdezd az edződet."),
        row("coach history notice", "a coach opens the message history and a player message matches the safety list", "Biztonsági jelzés — N játékosüzenet biztonságra utaló kifejezést tartalmaz. Olvasd el az üzenetet, és keresd meg a játékost személyesen."),
        row("coach history badge", "next to each such message", "Biztonsági jelzés"),
        "",
        "## 5. Keyword lists (false positives and misses)",
        "",
        "Safety (`safetyKeywords`, one list for guided chat and the coach; the last five are new): " + ", ".join("„" + k + "”" for k in a["safetyKeywords"]) + ".",
        "",
        "Pain or illness (`painKeywords`, new): " + ", ".join("„" + k + "”" for k in a["painKeywords"]) + ".",
        "",
        "Matching ignores accents and capitals; a word of five letters or more also matches words that start with it. `coach_router.SAFETY_OR_PAIN` is a wider list that only stops the rules from answering (the model then does, as before).",
        "",
        "## 6. Questions for the reviewer",
        "",
        "1. Are the two joining phrases in the safety message right, or should the authored texts be shown as two separate messages?",
        "2. Is “szólj azonnal egy felnőttnek” enough for a strong pain or breathing problem, or should it name a doctor or the emergency number? (I used no number.)",
        "3. Is “Személyre szabott tanácsot nem adok” the right way to decline advice, or too cold for a young person?",
        "4. Which extra phrases belong in the safety and pain lists? Which would wrongly trigger (for example “nincs értelme edzeni”)?",
        "5. Who should be told, besides the coaches who see the history badge, when a safety phrase appears?",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT), len(lines), "lines")


if __name__ == "__main__":
    main()
